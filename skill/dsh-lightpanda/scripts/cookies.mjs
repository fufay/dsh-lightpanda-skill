#!/usr/bin/env node
// cookie 导入/转换：把浏览器导出的 cookie 转成 lightpanda 可用格式。
// 用法:
//   node cookies.mjs convert --from playwright --in storageState.json --out cookies.json
//   node cookies.mjs convert --from playwright --in storageState.json --out cookies.txt --format netscape
//   node cookies.mjs inspect cookies.json
// 说明: lightpanda 的 --cookie 接受「CDP/Puppeteer JSON 数组」或「Netscape cookies.txt」。
import { readFileSync, writeFileSync } from 'node:fs';

const argv = process.argv.slice(2);
const cmd = argv[0];
const opt = (n, d) => { const i = argv.indexOf('--' + n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };

function fromPlaywright(state) {
  const list = state && Array.isArray(state.cookies) ? state.cookies : [];
  return list.map((c) => ({
    name: c.name,
    value: c.value,
    domain: c.domain,
    path: c.path || '/',
    expires: typeof c.expires === 'number' ? c.expires : -1,
    httpOnly: !!c.httpOnly,
    secure: !!c.secure,
    sameSite: c.sameSite || 'Lax',
  }));
}

function toNetscape(list) {
  const lines = ['# Netscape HTTP Cookie File', '# generated by dsh-lightpanda cookies.mjs', ''];
  for (const c of list) {
    const domain = c.domain;
    const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expiry = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    const httpOnly = c.httpOnly ? '#HttpOnly_' : '';
    lines.push([httpOnly + domain, includeSub, c.path || '/', c.secure ? 'TRUE' : 'FALSE', expiry, c.name, c.value].join('\t'));
  }
  return lines.join('\n') + '\n';
}

if (cmd === 'convert') {
  const from = opt('from', 'playwright');
  const input = opt('in', null);
  const output = opt('out', null);
  const format = opt('format', 'puppeteer');
  if (!input || !output) { console.error('用法: cookies.mjs convert --from playwright --in <state.json> --out <file> [--format puppeteer|netscape]'); process.exit(2); }
  const raw = JSON.parse(readFileSync(input, 'utf8'));
  let list;
  if (from === 'playwright') list = fromPlaywright(raw);
  else if (from === 'puppeteer' || from === 'cdp') list = Array.isArray(raw) ? raw : (raw.cookies || []);
  else { console.error('未知来源: ' + from); process.exit(2); }
  if (format === 'netscape') writeFileSync(output, toNetscape(list));
  else writeFileSync(output, JSON.stringify(list, null, 2));
  console.log(JSON.stringify({ ok: true, cookies: list.length, out: output, format }));
} else if (cmd === 'inspect') {
  const file = argv[1];
  if (!file) { console.error('用法: cookies.mjs inspect <cookies.json>'); process.exit(2); }
  const txt = readFileSync(file, 'utf8');
  let list;
  if (txt.trimStart().startsWith('[')) list = JSON.parse(txt);
  else list = txt.split('\n').filter((l) => l && !l.startsWith('#') || l.startsWith('#HttpOnly_')).map((l) => {
    const parts = l.replace(/^#HttpOnly_/, '').split('\t');
    return { name: parts[5], value: parts[6], domain: parts[0], path: parts[2], secure: parts[3] === 'TRUE', expires: Number(parts[4]) };
  });
  const domains = [...new Set(list.map((c) => c.domain))];
  const now = Math.floor(Date.now() / 1000);
  const expired = list.filter((c) => c.expires > 0 && c.expires < now).length;
  console.log(JSON.stringify({ cookies: list.length, domains: domains.slice(0, 20), expired }, null, 2));
} else {
  console.error('用法: cookies.mjs convert|inspect ...');
  process.exit(2);
}
